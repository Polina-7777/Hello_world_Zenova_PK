# Ввод количества чисел N
N = int(input("Введите количество чисел N: "))

# Ввод первого числа для инициализации max
A = float(input("Введите число: "))
max_val = A
i = 1

# Цикл (ромб: i < N)
while i < N:
    A = float(input("Введите следующее число: "))

    # Проверка условия (блок A > max)
    if A > max_val:
        max_val = A

    # Увеличение счетчика (блок i = i + 1)
    i = i + 1

# Вывод результата (фигура с волнистым краем: max)
print("Максимальное число:", max_val)