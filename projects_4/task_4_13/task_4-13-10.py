# 1. Ввод общего количества элементов N
N = int(input("Введите количество элементов массива N: "))

# Подготовка массива A (заполнение данными)
A = []
for k in range(N):
    val = float(input(f"Введите элемент A[{k}]: "))
    A.append(val)

# 2. Инициализация (прямоугольник: sum = 0, i = 1)
# Мы начинаем с i = 1, так как это первый нечетный индекс
total_sum = 0
i = 1

# 3. Цикл (ромб: i < N)
while i < N:
    # 4. Прибавление элемента с текущим нечетным индексом
    total_sum = total_sum + A[i]

    # 5. Шаг через один (прямоугольник: i = i + 2)
    # Это позволяет переходить сразу к следующему нечетному числу (1 -> 3 -> 5...)
    i = i + 2

# 6. Вывод результата (фигура с волной: sum)
print("Сумма элементов с нечетными индексами:", total_sum)