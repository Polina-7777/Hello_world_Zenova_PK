# Ввод числа N (параллелограмм)
N = int(input("Введите число N: "))

# Инициализация переменных (прямоугольник)
sum_sq = 0
i = 1

# Цикл (ромб: i <= N)
while i <= N:
    # Вычисление суммы квадратов (sum = sum + i * i)
    sum_sq = sum_sq + i * i

    # Увеличение счетчика (i = i + 1)
    i = i + 1

# Вывод итоговой суммы (фигура с волной)
print("Сумма квадратов первых N чисел:", sum_sq)