# 1. Ввод общего количества элементов N
N = int(input("Введите количество элементов массива N: "))

# Подготовка массива A (заполнение данными)
A = []
for idx in range(N):
    val = float(input(f"Введите элемент A[{idx}]: "))
    A.append(val)

# 2. Инициализация переменных (прямоугольник: sum=0, K=0, i=0)
total_sum = 0
K = 0
i = 0

# 3. Основной цикл (ромб: i < N)
while i < N:
    # Накопление суммы (sum = sum + A[i])
    total_sum = total_sum + A[i]

    # Подсчет количества взятых элементов (K = K + 1)
    K = K + 1

    # Переход к следующему четному индексу (i = i + 2)
    i = i + 2

# 4. Вычисление среднего (прямоугольник: Среднее M = sum / K)
if K > 0:
    M = total_sum / K
else:
    M = 0

# 5. Вывод результата (фигура с волной: Среднее M)
print("Среднее арифметическое элементов с четными индексами:", M)