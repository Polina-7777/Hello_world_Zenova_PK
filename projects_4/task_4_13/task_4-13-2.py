# Ввод данных (параллелограмм: A, B, C, D)
A = float(input("Введите число A: "))
B = float(input("Введите число B: "))
C = float(input("Введите число C: "))
D = float(input("Введите число D: "))

# Вычисление суммы (прямоугольник: Sum = A + B + C + D)
# Обратите внимание, что в Python регистр важен
Sum = A + B + C + D

# Вычисление среднего (прямоугольник: Avg = sum / 4)
Avg = Sum / 4

# Вывод результата (параллелограмм: Avg)
print("Среднее арифметическое (Avg):", Avg)
