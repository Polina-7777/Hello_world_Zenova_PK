# 1. Задаем массив (список) и его длину N
# В Python массив можно задать вручную или ввести с клавиатуры
a = [10, 20, 30, 40, 50]
N = len(a)

# 2. Инициализация переменных (прямоугольник: sum = 0, i = 0)
total_sum = 0
i = 0

# 3. Цикл (ромб: i < N)
while i < N:
    # Накопление суммы (sum = sum + a[i])
    total_sum = total_sum + a[i]

    # Увеличение индекса (i = i + 1)
    i = i + 1

# 4. Вычисление среднего (прямоугольник: avg = sum / N)
if N > 0:
    avg = total_sum / N
else:
    avg = 0

# 5. Вывод результата (фигура с волной: avg)
print("Среднее арифметическое элементов массива:", avg)