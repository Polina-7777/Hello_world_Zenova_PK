# 1. Ввод количества элементов N (параллелограмм)
N = int(input("Введите количество элементов массива N: "))

# Инициализация массива (подготовка данных для a[i])
a = []
for k in range(N):
    val = float(input(f"Введите элемент a[{k}]: "))
    a.append(val)

# 2. Инициализация переменных (прямоугольник: count = 0, i = 0)
count = 0
i = 0

# 3. Основной цикл (ромб: i < N)
while i < N:
    # 4. Проверка условия (второй ромб: a[i] > 0)
    if a[i] > 0:
        # Если "Да": увеличиваем счетчик
        count = count + 1

    # 5. Переход к следующему элементу (прямоугольник: i = i + 1)
    i = i + 1

# 6. Вывод результата (фигура с волной: count)
print("Количество положительных чисел:", count)