# 1. Ввод количества элементов N
N = int(input("Введите количество элементов массива N: "))

# Подготовка массива A (заполнение данными)
A = []
for k in range(N):
    val = int(input(f"Введите элемент A[{k}]: "))
    A.append(val)

# 2. Инициализация переменных (прямоугольник: sum = 0, i = 0)
total_sum = 0
i = 0

# 3. Главный цикл (верхний ромб: i < N)
while i < N:
    # 4. Проверка на нечетность (нижний ромб: A[i] % 2 != 0)
    if A[i] % 2 != 0:
        # Если "Да": добавляем элемент к сумме
        total_sum = total_sum + A[i]

    # 5. Переход к следующему индексу (прямоугольник: i = i + 1)
    # Этот шаг выполняется всегда, независимо от четности числа
    i = i + 1

# 6. Вывод результата (фигура с волной: sum)
print("Сумма нечетных элементов:", total_sum)