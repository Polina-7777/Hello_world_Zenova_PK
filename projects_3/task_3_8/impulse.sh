#!/bin/bash
if [ $# -eq 0 ]; then
    echo "Ошибка: не переданы входящие данные. Пожалуйста, укажите имя гена и уровень его экспрессии (целое число)."
    exit 1
fi
if [ $# -ne 2 ]; then
    echo "Ошибка: ожидается ровно два аргумента — имя гена и уровень экспрессии (целое число)."
    exit 1
fi
gene_name="$1"
expression_level="$2"
echo "Экспрессия гена $gene_name составляет $expression_level единиц"
